"""
The Medicare ASC rate lookup: what Medicare pays an ambulatory surgery center for any code on CMS's ASC addenda (AA and
BB), in any county, in the rule year, against the year before. The tables in remitwatch/cms are generated by
scripts/build_ascfs.py from ASCA's "Medicare ASC final rule rate calculator" workbook, and the amounts are worked out the
way that workbook works them out, so a code looked up here agrees with it to the cent:

    national       the rate (Addendum AA, else BB); the beneficiary's copayment: 20% of the rate rounded to the cent,
                   nothing for a preventive service CMS marks '**', a drug's inflation-adjusted copayment where Addendum
                   BB gives one; Medicare's payment is the rest
    local          Medicare's payment and the copayment each wage-adjusted, half of each by the county's ASC wage index
                   (42 CFR 416.172), Medicare's rounded to the cent; the indicators the calculator leaves as they stand
                   (drugs, brachytherapy sources, pass-through devices and the like) are not adjusted
    sequestration  2% off Medicare's payment, rounded to the cent; the copayment is not reduced

Medicare's own pricer adjusts the whole rate before taking the coinsurance from it (remitwatch.ascfs.asc_amount, which the
strategy lab and the ASC view's estimate use); the two ways can differ by a cent on a line.

Code numbers and amounts only: no CPT or CDT descriptions.
"""
from __future__ import annotations

import csv
import functools
import json
import re
from dataclasses import dataclass, field
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

DATA = Path(__file__).parent / "cms"      # CMS's published tables; "data/" is the practice's own and is never committed
CODE = re.compile(r"^[A-Z0-9]{1,5}$")
MAX_ROWS = 500


@dataclass
class Tables:
    meta: dict
    years: list[str]                                    # oldest first; the last is the rule year
    rates: dict[str, dict]                              # code -> {'apc': str, year: {pi, rate, copay, mpd, ci, add} | None}
    codes: list[str]                                    # sorted
    places: dict[tuple, dict] = field(default_factory=dict)    # (state, county) -> {state, county, fips, cbsa, cbsa_name, wi}
    by_fips: dict[str, dict] = field(default_factory=dict)


def _int(s: str) -> int | None:
    return int(s) if s not in (None, "") else None


@functools.lru_cache(maxsize=1)
def tables() -> Tables:
    """The generated tables, read once."""
    meta = json.loads((DATA / "asc_meta.json").read_text())
    rates: dict[str, dict] = {}
    with open(DATA / "asc_rates.csv", newline="") as fh:
        rd = csv.reader(fh)
        head = next(rd)
        years = sorted({h.rsplit("_", 1)[1] for h in head[2:]})
        idx = {h: i for i, h in enumerate(head)}
        for r in rd:
            row: dict = {"apc": r[1]}
            for y in years:
                if not r[idx[f"pi_{y}"]] and not r[idx[f"rate_{y}"]] and not r[idx[f"add_{y}"]]:
                    row[y] = None
                    continue
                row[y] = {"pi": r[idx[f"pi_{y}"]], "rate": _int(r[idx[f"rate_{y}"]]), "copay": _int(r[idx[f"copay_{y}"]]),
                          "mpd": r[idx[f"mpd_{y}"]], "ci": r[idx[f"ci_{y}"]], "add": r[idx[f"add_{y}"]]}
            rates[r[0]] = row
    t = Tables(meta=meta, years=years, rates=rates, codes=sorted(rates))
    with open(DATA / "asc_counties.csv", newline="") as fh:
        rd = csv.DictReader(fh)
        wcol = next(c for c in rd.fieldnames if c.startswith("wi_"))
        for r in rd:
            p = {"state": r["state"], "county": r["county"], "fips": r["fips"], "cbsa": r["cbsa"], "cbsa_name": r["cbsa_name"],
                 "wi": Decimal(r[wcol])}
            t.places[(r["state"], r["county"])] = p
            if r["fips"]:
                t.by_fips[r["fips"]] = p
    return t


def rule_year() -> str:
    return tables().meta["rule_year"]


def prior_year() -> str:
    return tables().meta["prior_year"]


def _cents(x: Decimal) -> int:
    """Half a cent and up away from zero, as the workbook's ROUND."""
    return int(x.quantize(Decimal(1), rounding=ROUND_HALF_UP))


def wage_adjusted(pi: str) -> bool:
    return pi not in tables().meta["not_wage_adjusted"]


def amounts(rate: int | None, copay: int | None, wi: Decimal | float | str | None = None, adjusted: bool = True) -> dict | None:
    """One code's amounts in cents, as the calculator lays them out: the total payment (Medicare's and the copayment),
    Medicare's payment, the copayment, the 2% sequestration of Medicare's payment, and Medicare's payment and the total
    after it. National with no wage index; local with the county's. None where the code has no rate."""
    if rate is None:
        return None
    copay = copay or 0
    med = rate - copay
    if wi is not None and adjusted:
        half = Decimal(str(tables().meta["labor_share"]))
        adj = Decimal(str(wi)) * half + (1 - half)
        med_l = _cents(Decimal(med) * adj)
        cop = Decimal(copay) * adj                     # not rounded until shown, as in the workbook
    else:
        med_l, cop = med, Decimal(copay)
    seq = _cents(Decimal(med_l) * Decimal(str(tables().meta["sequestration"])))
    return {"total": _cents(med_l + cop), "medicare": med_l, "copay": _cents(cop), "seq": seq,
            "medicare_after": med_l - seq, "total_after": _cents(med_l - seq + cop)}


def place(state: str | None = None, county: str | None = None, fips: str | None = None) -> dict | None:
    """A county as the calculator's picker names it (state abbreviation and county, upper case), or by FIPS code."""
    t = tables()
    if fips:
        return t.by_fips.get(fips)
    if state and county:
        return t.places.get((state.strip().upper(), " ".join(county.split()).upper()))
    return None


def office_place(office: str) -> dict | None:
    """The county of one of the practice's offices (remitwatch.ascfs.OFFICE_COUNTY)."""
    from .ascfs import OFFICE_COUNTY
    f = OFFICE_COUNTY.get(office)
    return place(fips=f) if f else None


def office_wage_index(office: str, year: str) -> Decimal | None:
    """The office's ASC wage index for a year: the county's for the rule year, the generated table's for the year before."""
    from .ascfs import WAGE_INDEX
    wi = WAGE_INDEX.get(year, {}).get(office)
    return Decimal(str(wi)) if wi is not None else None


def places() -> dict:
    """The picker: states (abbreviation, name) and each state's counties."""
    t = tables()
    names = t.meta.get("states", {})
    counties: dict[str, list] = {}
    for (st, county), p in sorted(t.places.items()):
        counties.setdefault(st, []).append([county, p["fips"]])
    states = sorted(((st, names.get(st, st)) for st in counties), key=lambda s: s[1])
    return {"states": [list(s) for s in states], "counties": counties}


def status(code: str) -> str:
    """'New' or 'Revised' in the rule year, as the calculator marks it: a comment indicator of a new code (NC, NI, NP) or
    a code not on the year before's addenda is new, CH is revised; a deleted code (D5) is neither."""
    t = tables()
    y, p = t.years[-1], t.years[0] if len(t.years) > 1 else None
    r = t.rates.get(code, {}).get(y)
    if not r or r["pi"] == "D5":
        return ""
    if r["ci"] == "CH":
        return "Revised"
    if r["ci"] in ("NC", "NI", "NP") or (p and not t.rates[code].get(p)):
        return "New"
    return ""


def _match(query: str) -> list[str]:
    """Codes a search names: whole codes, the start of a code ('1404'), or a range ('11600-11646'), separated by spaces
    or commas. An empty search is every code."""
    t = tables()
    q = (query or "").upper().replace(",", " ").split()
    if not q:
        return list(t.codes)
    out: set[str] = set()
    for tok in q[:200]:
        if "-" in tok:
            a, _, b = tok.partition("-")
            if CODE.match(a) and CODE.match(b) and a <= b:
                # each end as far as it is typed: '116-117' is every code from 116.. through 117..
                out.update(c for c in t.codes if c[:len(a)] >= a and c[:len(b)] <= b)
            continue
        if CODE.match(tok):
            out.update(c for c in t.codes if c.startswith(tok))
    return sorted(out)


def row(code: str, where: dict | None = None, prior_wi: Decimal | None = None) -> dict | None:
    """One code's line: its indicators and its amounts, national and (with a county) local, in the rule year; the year
    before's indicator and national rate, and its local total where that year's wage index for the county is known."""
    t = tables()
    rates = t.rates.get(code)
    if rates is None:
        return None
    y, p = t.years[-1], (t.years[0] if len(t.years) > 1 else None)
    cur, old = rates.get(y), rates.get(p) if p else None
    out: dict = {"code": code, "apc": rates["apc"], "listed": cur is not None, "status": status(code)}
    if cur:
        adj = wage_adjusted(cur["pi"])
        out.update({"pi": cur["pi"], "mpd": cur["mpd"], "ci": cur["ci"], "add": cur["add"], "adjusted": adj,
                    "national": amounts(cur["rate"], cur["copay"]),
                    "local": amounts(cur["rate"], cur["copay"], where["wi"], adj) if where else None})
    if old:
        out["prior"] = {"pi": old["pi"], "rate": old["rate"]}
        if prior_wi is not None and old["rate"] is not None:
            a = amounts(old["rate"], old["copay"], prior_wi, wage_adjusted(old["pi"]))
            out["prior"]["local_total"] = a["total"] if a else None
    if cur and old and cur["rate"] is not None and old["rate"] is not None:
        out["change"] = cur["rate"] - old["rate"]
        out["change_pct"] = round(cur["rate"] / old["rate"] - 1, 4) if old["rate"] else None
    return out


def lookup(query: str = "", state: str | None = None, county: str | None = None, offset: int = 0, limit: int = 100) -> dict:
    """The calculator's table for a search and a county: up to `limit` codes from `offset`, and how many match."""
    t = tables()
    where = place(state, county)
    prior_wi = None
    if where and where.get("fips"):
        from .ascfs import OFFICE_COUNTY
        office = next((o for o, f in OFFICE_COUNTY.items() if f == where["fips"]), None)
        if office:
            prior_wi = office_wage_index(office, t.years[0])
    codes = _match(query)
    limit = max(1, min(int(limit), MAX_ROWS))
    offset = max(0, int(offset))
    page = codes[offset:offset + limit]
    m = t.meta
    return {
        "rule_year": t.years[-1], "prior_year": t.years[0] if len(t.years) > 1 else None, "years": m.get("years", {}),
        "source": m.get("source"), "labor_share": m.get("labor_share"), "sequestration": m.get("sequestration"),
        "not_wage_adjusted": m.get("not_wage_adjusted", []),
        "place": ({k: (str(v) if k == "wi" else v) for k, v in where.items()} | {"prior_wi": str(prior_wi) if prior_wi is not None else None})
        if where else None,
        "query": query or "", "total": len(codes), "offset": offset, "limit": limit,
        "rows": [r for c in page for r in [row(c, where, prior_wi)] if r],
    }


def definitions() -> dict:
    """Addendum DD1: what each payment indicator means."""
    return dict(tables().meta.get("pi", {}))
